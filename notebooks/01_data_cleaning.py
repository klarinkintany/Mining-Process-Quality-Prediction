import pandas as pd

file_path = "/content/mining_quality_data/MiningProcess_Flotation_Plant_Database.csv"

df = pd.read_csv(file_path, sep=",", low_memory=False)

print("Ukuran dataset:", df.shape)
print("\nNama kolom:")
print(df.columns.tolist())

display(df.head())

"""Periksa struktur dan nilai kosong"""

# 1. Informasi tipe data dan jumlah nilai non-null
print("=== INFO DATASET ===")
df.info()

# 2. Periksa missing values
print("\n=== MISSING VALUES ===")
print(df.isnull().sum())

# 3. Periksa jumlah baris duplikat
print("\n=== DUPLICATE ROWS ===")
print("Jumlah duplikat:", df.duplicated().sum())

"""Periksa tipe data dan duplikat"""

# Periksa tipe data setiap kolom
print("=== TIPE DATA ===")
print(df.dtypes.value_counts())

# Periksa beberapa nilai tanggal
print("\n=== CONTOH TANGGAL ===")
print(df["date"].head(10).to_string(index=False))

# Periksa contoh baris duplikat
print("\n=== CONTOH BARIS DUPLIKAT ===")
display(df[df.duplicated(keep=False)].head(10))

"""Hitung duplikat berdasarkan tanggal"""

# Pastikan kolom tanggal terbaca sebagai datetime
df["date"] = pd.to_datetime(
    df["date"],
    format="%Y-%m-%d %H:%M:%S",
    errors="coerce"
)

# Periksa tanggal yang gagal dikonversi
print("Tanggal tidak valid:", df["date"].isna().sum())

# Periksa timestamp yang berulang
print("Jumlah timestamp duplikat:",
      df["date"].duplicated().sum())

print("\nContoh timestamp yang berulang:")
display(
    df[df["date"].duplicated(keep=False)]
    [["date"]]
    .head(10)
)

"""Pastikan apakah seluruh nilai sensor juga sama"""

# Cek duplikat berdasarkan seluruh kolom
print(
    "Duplikat seluruh baris:",
    df.duplicated().sum()
)

# Tampilkan data pada timestamp pertama
first_time = df["date"].iloc[0]

print("\nTimestamp yang diperiksa:", first_time)

display(
    df[df["date"] == first_time].head(10)
)

"""Mengubah kolom numerik dari teks menjadi angka

Apa yang ingin kita pastikan?
- Kolom date tetap bertipe tanggal.
- Kolom sensor dan kualitas berubah menjadi numerik.
- Tidak ada nilai yang gagal dikonversi menjadi angka.
- Statistik deskriptif bisa dihitung.
"""

# Simpan salinan data mentah untuk keamanan
df_raw = df.copy()

# Konversi semua kolom selain date menjadi numerik
numeric_cols = df.columns.drop("date")

for col in numeric_cols:
    df[col] = pd.to_numeric(
        df[col].astype(str).str.replace(",", ".", regex=False),
        errors="coerce"
    )

print("Tipe data setelah konversi:")
print(df.dtypes.value_counts())

print("\nJumlah nilai kosong setelah konversi:")
print(df.isna().sum().sum())

print("\nStatistik deskriptif:")
display(df.describe().T.head(10))

"""Periksa kualitas data setelah konversi

Apa yang kita cari?
- Apakah jumlah baris dan kolom tetap konsisten?
- Apakah kolom sensor sekarang bertipe angka?
- Apakah proses konversi menimbulkan nilai kosong baru?
- Berapa rentang waktu data yang tersedia?
- Bagaimana distribusi awal kedua indikator kualitas produk?
"""

# 1. Periksa ukuran dataset
print("Ukuran dataset:", df.shape)

# 2. Periksa tipe data
print("\nTipe data:")
print(df.dtypes.value_counts())

# 3. Periksa missing values per kolom
print("\nMissing values per kolom:")
print(df.isna().sum().sort_values(ascending=False))

# 4. Periksa rentang tanggal
print("\nPeriode dataset:")
print("Mulai:", df["date"].min())
print("Selesai:", df["date"].max())

# 5. Periksa statistik target kualitas
targets = ["% Iron Concentrate", "% Silica Concentrate"]

print("\nStatistik kualitas produk:")
display(df[targets].describe().T)

print("Dataset shape:", df.shape)

print("\nTipe data:")
print(df.dtypes.value_counts())

print("\nMissing values total:", df.isna().sum().sum())

print("\nDuplikat seluruh baris:", df.duplicated().sum())

print("\nRentang tanggal:")
print(df["date"].min(), "sampai", df["date"].max())

"""Bersihkan duplikat dengan hati-hati"""

# Simpan data asli agar tetap tersedia
df_raw = df.copy()

# Hapus baris yang identik pada seluruh kolom
df_clean = df.drop_duplicates().copy()

print("Jumlah baris sebelum:", len(df_raw))
print("Jumlah baris sesudah:", len(df_clean))
print("Baris yang dihapus:", len(df_raw) - len(df_clean))
print("Duplikat tersisa:", df_clean.duplicated().sum())

"""Validasi tipe data"""

# Periksa tipe data setelah cleaning
print("=== VALIDASI TIPE DATA ===")
print(df_clean.dtypes.value_counts())

# Pastikan kolom tanggal bertipe datetime
print("\nTipe data tanggal:", df_clean["date"].dtype)

# Periksa nilai kosong
print("\nTotal missing values:", df_clean.isna().sum().sum())

# Periksa duplikat yang tersisa
print("Duplikat tersisa:", df_clean.duplicated().sum())

"""Simpan dataset bersih"""

import os

output_dir = "/content/mining_quality_data/processed"
os.makedirs(output_dir, exist_ok=True)

output_path = os.path.join(
    output_dir,
    "mining_process_clean.csv"
)

df_clean.to_csv(output_path, index=False)

print("Dataset bersih berhasil disimpan!")
print("Lokasi:", output_path)
print("Ukuran dataset:", df_clean.shape)

